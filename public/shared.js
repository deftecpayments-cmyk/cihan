/* ===== Languages List ===== */
const languages = [
  { code: 'ku', label: 'کوردی', dir: 'rtl' },
  { code: 'ar', label: 'العربية', dir: 'rtl' },
  { code: 'en', label: 'English', dir: 'ltr' }
];

/* ===== Language Management ===== */
function getLang() {
  try {
    return localStorage.getItem('cb-lang') || 'ku';
  } catch (e) {
    return 'ku';
  }
}

function setLang(code) {
  try {
    localStorage.setItem('cb-lang', code);
  } catch (e) {
    // localStorage unavailable
  }
}

function t(key) {
  var lang = getLang();
  if (translations[lang] && translations[lang][key]) {
    return translations[lang][key];
  }
  // fallback to Kurdish, then English
  if (translations.ku && translations.ku[key]) return translations.ku[key];
  if (translations.en && translations.en[key]) return translations.en[key];
  return key;
}

function getLangDir() {
  var lang = getLang();
  var found = languages.find(function(l) { return l.code === lang; });
  return found ? found.dir : 'rtl';
}

function getLangObj() {
  var lang = getLang();
  return languages.find(function(l) { return l.code === lang; }) || languages[0];
}

/* ===== Apply Language to Document ===== */
function applyLang() {
  var langObj = getLangObj();
  document.documentElement.lang = langObj.code;
  document.documentElement.dir = langObj.dir;
}

/* ===== Language Switcher HTML Generator ===== */
function renderLangSwitcher(containerId) {
  var container = document.getElementById(containerId);
  if (!container) return;

  var currentLang = getLangObj();

  var html = '<div class="lang-switcher">';
  html += '<button class="lang-btn" id="langToggle" aria-label="' + t('language') + '">';
  html += '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><circle cx="12" cy="12" r="10"/><line x1="2" y1="12" x2="22" y2="12"/><path d="M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z"/></svg>';
  html += '<span>' + currentLang.label + '</span>';
  html += '</button>';
  html += '<div class="lang-dropdown" id="langDropdown">';

  languages.forEach(function(lang) {
    var activeClass = lang.code === currentLang.code ? ' active' : '';
    html += '<button class="lang-option' + activeClass + '" data-lang="' + lang.code + '">' + lang.label + '</button>';
  });

  html += '</div></div>';
  container.innerHTML = html;

  // Bind events
  var toggleBtn = document.getElementById('langToggle');
  var dropdown = document.getElementById('langDropdown');

  toggleBtn.addEventListener('click', function(e) {
    e.stopPropagation();
    dropdown.classList.toggle('open');
  });

  dropdown.querySelectorAll('.lang-option').forEach(function(btn) {
    btn.addEventListener('click', function() {
      var newLang = this.getAttribute('data-lang');
      setLang(newLang);
      applyLang();
      dropdown.classList.remove('open');
      if (typeof renderPage === 'function') {
        renderPage();
      }
    });
  });

  // Close dropdown when clicking outside
  document.addEventListener('click', function() {
    dropdown.classList.remove('open');
  });
}

/* ===== Back Button HTML ===== */
function backButtonHTML(href) {
  href = href || 'home.html';
  var chevronSVG = getLangDir() === 'rtl'
    ? '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><polyline points="9 18 15 12 9 6"/></svg>'
    : '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><polyline points="15 18 9 12 15 6"/></svg>';
  return '<a href="' + href + '" class="back-btn">' + chevronSVG + '<span>' + t('back') + '</span></a>';
}

/* ===== Number Formatting ===== */
function formatNumber(num) {
  return Number(num).toLocaleString('en-US');
}
